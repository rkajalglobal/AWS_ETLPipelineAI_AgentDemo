-- Synthetic medical data only; not real patient information.

CREATE SCHEMA IF NOT EXISTS public;

CREATE TABLE public.departments (department_id INTEGER PRIMARY KEY, department_name VARCHAR NOT NULL UNIQUE, floor_number INTEGER);

CREATE TABLE public.doctors (doctor_id INTEGER PRIMARY KEY, first_name VARCHAR NOT NULL, last_name VARCHAR NOT NULL, specialty VARCHAR NOT NULL, department_id INTEGER NOT NULL REFERENCES public.departments(department_id));

CREATE TABLE public.patients (patient_id INTEGER PRIMARY KEY, first_name VARCHAR NOT NULL, last_name VARCHAR NOT NULL, date_of_birth DATE NOT NULL, city VARCHAR, registration_date DATE NOT NULL);

CREATE TABLE public.appointments (appointment_id INTEGER PRIMARY KEY, patient_id INTEGER NOT NULL REFERENCES public.patients(patient_id), doctor_id INTEGER NOT NULL REFERENCES public.doctors(doctor_id), appointment_date DATE NOT NULL, appointment_time TIME NOT NULL, status VARCHAR NOT NULL, reason VARCHAR);

CREATE TABLE public.diagnoses (diagnosis_id INTEGER PRIMARY KEY, appointment_id INTEGER NOT NULL REFERENCES public.appointments(appointment_id), diagnosis_code VARCHAR NOT NULL, diagnosis_description VARCHAR NOT NULL);

CREATE TABLE public.medications (medication_id INTEGER PRIMARY KEY, medication_name VARCHAR NOT NULL UNIQUE, category VARCHAR NOT NULL, department_id INTEGER NOT NULL REFERENCES public.departments(department_id), price_usd DECIMAL(10,2) NOT NULL CHECK(price_usd >= 0));

CREATE TABLE public.prescriptions (prescription_id INTEGER PRIMARY KEY, appointment_id INTEGER NOT NULL REFERENCES public.appointments(appointment_id), medication_id INTEGER NOT NULL REFERENCES public.medications(medication_id), dosage VARCHAR NOT NULL, duration_days INTEGER NOT NULL CHECK(duration_days > 0));

